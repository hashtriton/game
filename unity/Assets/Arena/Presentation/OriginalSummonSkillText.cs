                case "AEer":return "Обездвиживает выбранного противника, запрещает атаки и наносит периодический урон. Применение способностей остается доступным.";
                case "AEsh":return "Наносит начальный и периодический урон, временно замедляя цель.";
                case "Aprg":return "Снимает поддерживаемые эффекты и временно замедляет выбранную цель.";
                case "Aply":return "На время превращает цель: запрещает атаки и способности, ограничивая скорость движения.";
                default:return "";
            }
        }
    }
}
