using System;
using Arena.Original;

namespace Arena
{
    // Read-only descriptions of the host's implemented summon command paths.
    // Resource/readiness values are published independently by the host DTO.
    public static class OriginalSummonSkillText
    {
        public static string Describe(OriginalGameCatalogs catalogs,string id,int rank=1)
        {
            if(catalogs==null)throw new ArgumentNullException(nameof(catalogs));
            return Describe(catalogs.Combat,id,rank);
        }
        public static string Describe(OriginalCombatCatalog combat,string id,int rank=1)
        {
            if(combat==null)throw new ArgumentNullException(nameof(combat));
            if(rank!=1)return "";
            switch(id)
            {
                case "A0FD":return "Восстанавливает выбранному раненому союзнику 50 здоровья. Перед этим союзники в радиусе 500 вокруг цели получают лечение в размере 5% ее максимального здоровья.";
                case "A030":return "На 20 с увеличивает скорость атаки союзника на 50%, скорость движения на 10%.";
                case "A0A2":return "Усыпляет противника на 4 с для героя или на 12 с для другого существа. Первые 2 с сон защищает от урона; поздний положительный урон будит цель.";
                case "A0WH":return "Раскрывает невидимых противников в радиусе 1000 на 8 с.";
                case "A18J":return "Посылает снаряд в указанную точку. По прибытии сети обездвиживают подходящих наземных врагов в радиусе 200 на 3 с, сохраняя возможность атаковать и применять способности.";
                case "A18I":return "Дает союзнику щит с запасом 600 на 8 с. Щит восстанавливает полученный урон с небольшой задержкой и расходует половину восстановленной суммы. Через 8 с или при смерти цели союзники в радиусе 500 получают лечение в размере половины записанного урона.";
                case "A05Y":return "Переключает огненный покров: наносит периодический урон ближайшим врагам и расходует ману. Повторное применение отключает покров без расхода маны.";
                case "A15T":return "Подпрыгивает на месте и при приземлении поражает врагов в радиусе 350 магическим уроном: 750, на сложности Extreme - 1500.";
                case "A0TR":return "В течение примерно 3,9 с притягивает противников из радиуса 1200 к месту применения.";
                case "A11L":return "Перемещается к автоматически выбранной точке арены.";
                case "A1DB":return "После подготовки совершает рывок к автоматически выбранному герою: наносит задетым врагам 400 магического урона и отталкивает героев вокруг конечной точки.";
                case "A1DD":case "A1DI":return "Связывает автоматически выбранные цели на время действия способности.";
            }
            switch(combat.Ability(id)?.Text("code"))
            {
                case "AOws":case "ACtc":case "ANht":return "Поражает подходящих противников вокруг выбранного существа.";
                case "Aslo":return "Замедляет движение и атаки выбранного противника.";
                case "Acri":return "Ослабляет базовый урон, скорость движения и атак выбранного противника.";
                case "Arej":return "Постепенно восстанавливает здоровье выбранного союзника.";
                case "AUdc":return "Поражает живого противника либо лечит союзную нежить.";
                case "AUfn":return "Поражает выбранного противника ледяным взрывом и замедляет ближайшие цели.";
                case "AEmb":return "Сжигает ману выбранного противника и наносит связанный с ней урон.";
