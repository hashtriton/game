                        if (Try("DataB", out double incoming) && incoming < 1) Add("Уменьшает входящий урон оружия на " + N((1 - incoming) * 100) + "%.");
                        break;
                    case "Assk":
                        if (Try("DataA", out double blockChance) && Try("DataB", out double floor) && Try("DataC", out double block) &&
                            Try("DataD", out double ranged) && Try("DataE", out double melee) && (ranged == 1 || melee == 1))
                            Add("С шансом " + N(blockChance) + "% блокирует " + N(block) + " урона " +
