        public string DescribePassive(string itemId)
        {
            if (string.IsNullOrEmpty(itemId)) return "";
            string id = items.FromWorld(itemId)?.inventoryId ?? itemId;
            if (items.Item(id) == null) return "";
            var bag = new OriginalInventorySnapshot { ownerId = 1,
                heroSlots = new OriginalItemInstance[6], servantSlots = new OriginalItemInstance[6] };
            bag.heroSlots[0] = new OriginalItemInstance { ownerId = 1, instanceId = 1, itemId = id };
            var lines = new List<string>();
            void Add(string line) { if (!string.IsNullOrEmpty(line) && !lines.Contains(line)) lines.Add(line); }
            foreach (var row in effects.CombatAbilities(bag))
            {
                var ability = combat.Ability(row.abilityId); if (ability == null || row.rank < 1) continue;
                string rank = row.rank.ToString(CultureInfo.InvariantCulture), code = ability.Text("code");
                bool Try(string key, out double value) => ability.TryNumber(key + rank, out value, out _);
                string Duration() => Try("Dur", out double ordinary) && Try("HeroDur", out double hero)
