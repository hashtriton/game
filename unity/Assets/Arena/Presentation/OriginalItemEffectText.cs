                        string target = (ability.Text("targs" + rank) ?? "").Contains("air") ? "цель" : "наземную цель";
                        string bonus = Try("DataC", out double damage) && damage > 0 ? " и нанести " + N(damage) + " дополнительного магического урона" : "";
                        Add("При атаке: шанс " + N(bash) + "% оглушить " + target + " на " + Duration() + bonus + ".");
                        break;
                    case "Afbk":
                        if (Try("DataA", out double burn) && Try("DataC", out double heroBurn) &&
                            Try("DataB", out double burnFactor) && Try("DataD", out double heroFactor))
                            Add("Попадание сжигает до " + N(burn) + " маны (у героя: " + N(heroBurn) + ") и добавляет физический урон " +
                                N(burnFactor * 100) + "% сожжённого (по герою: " + N(heroFactor * 100) + "%). Не действует на невосприимчивых к магии.");
                        break;
                    case "AIva":
                        if (Try("DataA", out double life)) Add("Вампиризм атак: " + N(life * 100) + "% фактически снятого здоровья основной цели. Не работает на зданиях и механических целях. Из орбов действует первый по порядку ячеек инвентаря.");
