        string Aura(OriginalCombatDefinition ability, int rank)
        {
            string n = rank.ToString(CultureInfo.InvariantCulture), code = ability.Text("code");
            if (!ability.TryNumber("Area" + n, out double radius, out _)) return "";
            var flags = (ability.Text("targs" + n) ?? "").Split(',');
            bool Has(string value) => Array.IndexOf(flags, value) >= 0;
            string recipients = Has("friend") || Has("allies") ? "союзникам" : Has("enemy") || Has("enemies") ? "врагам" : "только владельцу";
            if (Has("friend") || Has("allies")) recipients += Has("self") ? " и владельцу" : " (кроме владельца)";
            if (Has("hero") != Has("nonhero")) recipients += Has("hero") ? ", только героям" : ", кроме героев";
            string prefix = "Аура " + N(radius) + ": " + recipients + " ";
            bool Try(string key, out double value) => ability.TryNumber(key + n, out value, out _);
            double Optional(string key) => Try(key, out double value) ? value : 0;
            var values = new List<string>();
            void Bonus(double amount, string label) { if (amount != 0) values.Add((amount > 0 ? "+" : "") + N(amount) + label); }
            if (ability.id == "A1CS") return prefix + "раз в секунду восстанавливает 0,5% максимального здоровья и маны. Несколько таких аур не умножают восстановление.";
            if (code == "AUav" && Try("DataA", out double life))
                return prefix + "даёт " + N(life * 100) + "% вампиризма атак ближнего боя. Считается фактически снятое здоровье основной цели; здания, механические и невосприимчивые к магии цели исключены. Из таких аур действует сильнейшая.";
            switch (code)
            {
                case "AHad": case "AHab": case "Aoar": case "Aarm":
                    if (!Try("DataA", out double a)) return "";
                    bool percent = Optional("DataB") == 1;
                    Bonus(percent ? a * 100 : a, code == "AHad" ? (percent ? "% к базовой броне" : " брони") :
                        code == "Aoar" ? (percent ? "% максимального здоровья/с" : " здоровья/с") :
                        (percent ? "% максимальной маны/с" : " маны/с")); break;
                case "AUau": Bonus(Optional("DataA") * 100, "% скорости движения");
                    Bonus(Optional("DataB") * (Optional("DataC") == 1 ? 100 : 1), Optional("DataC") == 1 ? "% максимального здоровья/с" : " здоровья/с"); break;
                case "AOae": Bonus(Optional("DataA") * 100, "% скорости движения"); Bonus(Optional("DataB") * 100, "% скорости атаки"); break;
                case "Aakb":
                    if (!Try("DataA", out double attack) || (Optional("DataB") != 1 && Optional("DataC") != 1)) return "";
                    Bonus(attack * 100, "% базового урона " + (Optional("DataB") == 1 && Optional("DataC") == 1 ? "атак" : Optional("DataB") == 1 ? "ближних атак" : "дальних атак")); break;
            }
            if (values.Count == 0) return "";
            return prefix + string.Join(", ", values) + ". Одинаковые ауры не складываются.";
        }

        string A(string itemId, string field)
        {
            var item = items.Item(itemId);
            var ability = combat.Ability(item.cooldownId);
            if (ability == null || !ability.TryNumber(field, out double number, out _))
                foreach (string raw in item.abilityIds)
                {
                    ability = combat.Ability(raw);
                    if (ability != null && ability.TryNumber(field, out number, out _)) return N(number);
                }
            else return N(number);
            throw new InvalidOperationException("Missing item description field: " + itemId + "/" + field);
        }
        static string N(double value) => value.ToString("0.##", CultureInfo.GetCultureInfo("ru-RU"));
    }
